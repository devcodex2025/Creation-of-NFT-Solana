import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import * as path from "node:path";
import { Keypair } from "@solana/web3.js";

function findRepoRoot(start: string): string {
  let dir = path.resolve(start);
  for (;;) {
    if (existsSync(path.join(dir, "package.json"))) return dir;
    const parent = path.dirname(dir);
    if (parent === dir) return path.resolve(start);
    dir = parent;
  }
}

// `__dirname` is unreliable under some TS runners (esrun bundles modules into
// a virtual path), so anchor the project root to the working directory.
export const repoRoot = findRepoRoot(process.cwd());

export const defaultKeypairPath = path.join(repoRoot, "keypair.json");

export const solanaCliKeypairPath = path.join(
  homedir(),
  ".config",
  "solana",
  "id.json",
);

/**
 * Restricts a keypair file to its owner when POSIX mode bits are available.
 * Windows does not expose those bits, so the check runs only where they mean
 * something.
 */
function enforceOwnerOnlyPermissions(resolved: string): void {
  if (process.platform === "win32") return;
  try {
    const mode = statSync(resolved).mode & 0o777;
    if ((mode & 0o077) !== 0) {
      chmodSync(resolved, 0o600);
      console.warn(
        `Warning: ${resolved} was readable by other local users; restricted it to mode 600.`,
      );
    }
  } catch {
    // A stat failure here is not fatal; reading the file will report the real error.
  }
}

export function resolveKeypairPath(explicit?: string): string {
  // An explicitly requested wallet must exist. Falling back to a different
  // keypair here would silently pay fees from the wrong account.
  const requested = explicit ?? process.env.KEYPAIR_PATH;
  if (requested) {
    const resolved = path.resolve(requested);
    if (existsSync(resolved)) return resolved;
    throw new Error(
      [
        `Keypair not found at ${resolved}.`,
        "Check --keypair or KEYPAIR_PATH.",
        "Refusing to fall back to another wallet, because that would pay from a different account.",
      ].join("\n"),
    );
  }

  // Only the project's own keypair is read without being asked. Another app's
  // wallet file (for example the Solana CLI keypair) requires an explicit
  // --keypair or KEYPAIR_PATH, so the toolkit never pays from a wallet the
  // user did not name.
  if (existsSync(defaultKeypairPath)) return defaultKeypairPath;

  throw new Error(
    [
      "No keypair found.",
      `Looked in: ${defaultKeypairPath}`,
      "Create one with `npm run keypair` (writes keypair.json in the project root),",
      `or set KEYPAIR_PATH to the wallet you want to use, for example KEYPAIR_PATH=${solanaCliKeypairPath}.`,
      "The Solana CLI wallet is not read implicitly, so a run can never pay from a wallet you did not choose.",
    ].join("\n"),
  );
}

export function loadSecretKey(keypairPath?: string): Uint8Array {
  const resolved = resolveKeypairPath(keypairPath);
  enforceOwnerOnlyPermissions(resolved);
  const raw = readFileSync(resolved, "utf8");

  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    throw new Error(
      `${resolved} is not valid JSON. A Solana keypair is a JSON array of 64 bytes, ` +
        "as produced by `solana-keygen new` or `npm run keypair`.",
    );
  }

  if (!Array.isArray(parsed) || parsed.some((byte) => typeof byte !== "number")) {
    throw new Error(
      `${resolved} must contain a JSON array of numbers (the 64-byte secret key).`,
    );
  }

  const secretKey = Uint8Array.from(parsed as number[]);
  if (secretKey.length !== 64) {
    throw new Error(
      `${resolved} contains ${secretKey.length} bytes; a Solana secret key must be 64 bytes.`,
    );
  }

  return secretKey;
}

export function loadKeypair(keypairPath?: string): Keypair {
  const secretKey = loadSecretKey(keypairPath);
  try {
    return Keypair.fromSecretKey(secretKey);
  } finally {
    // fromSecretKey copies the bytes, so the caller's copy can be wiped.
    secretKey.fill(0);
  }
}

export interface CreatedKeypair {
  keypairPath: string;
  publicKey: string;
}

export function createKeypairFile(
  keypairPath: string = defaultKeypairPath,
): CreatedKeypair {
  const resolved = path.resolve(keypairPath);
  if (existsSync(resolved)) {
    throw new Error(
      `Refusing to overwrite ${resolved}. Delete it first if you really want a new keypair.`,
    );
  }

  const keypair = Keypair.generate();
  const publicKey = keypair.publicKey.toBase58();
  const secret = Array.from(keypair.secretKey);
  // The generated bytes are written once and then wiped from this object.
  keypair.secretKey.fill(0);
  mkdirSync(path.dirname(resolved), { recursive: true });
  writeFileSync(resolved, JSON.stringify(secret), { mode: 0o600 });
  secret.fill(0);
  // The mode argument is filtered through the umask; chmod makes it explicit.
  if (process.platform !== "win32") chmodSync(resolved, 0o600);

  return {
    keypairPath: resolved,
    publicKey,
  };
}
